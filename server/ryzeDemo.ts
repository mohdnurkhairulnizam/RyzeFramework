export type DemoAction = "remember" | "recall" | "inspect_upload" | "generate_note" | "retry_demo" | "safe_analysis" | "blocked";
export type DemoAttempt = { attempt: number; outcome: "success" | "recoverable"; message: string };

const BLOCKED_PATTERNS = [
  /\b(shell|bash|powershell|cmd\.exe|sudo|terminal)\b/i,
  /\b(send email|telegram|whatsapp|post to|publish to)\b/i,
  /\b(api key|secret key|password)\b/i,
];

export function determineDemoAction(prompt: string): DemoAction {
  const normalized = prompt.trim().toLowerCase();
  if (BLOCKED_PATTERNS.some((pattern) => pattern.test(normalized))) return "blocked";
  if (/^(remember|memorize|keep in mind)\b/.test(normalized)) return "remember";
  if (/^(recall|search memory|what do you know)\b/.test(normalized)) return "recall";
  if (/\b(inspect|review|check)\b.*\b(upload|file|document)\b/.test(normalized)) return "inspect_upload";
  if (/\b(generate|create|write)\b.*\b(note|briefing|summary|document)\b/.test(normalized)) return "generate_note";
  if (/\bretry demo\b/.test(normalized)) return "retry_demo";
  return "safe_analysis";
}

export function boundedDemoAttempts(action: DemoAction, maxAttempts = 3): DemoAttempt[] {
  if (!Number.isInteger(maxAttempts) || maxAttempts < 1) throw new Error("maxAttempts must be at least 1.");
  if (action !== "retry_demo") {
    return [{ attempt: 1, outcome: "success", message: "Allowlisted step completed on the first attempt." }];
  }
  const retryAttempts: DemoAttempt[] = [
    { attempt: 1, outcome: "recoverable", message: "Demo parser returned a simulated recoverable warning." },
    { attempt: 2, outcome: "success", message: "Ryze corrected the delegate instruction and Nerd completed the retry." },
  ];
  return retryAttempts.slice(0, maxAttempts);
}

export function makeGeneratedNote(prompt: string, taskId: string): string {
  return `# PROJECT RYZE Sandbox Note\n\n**Task ID:** ${taskId}\n\n${prompt.trim()}\n\n---\nGenerated by the safe Ryze → Nerd demonstration workflow. No external model, shell command, email, or Telegram action was used.`;
}

export function memoryQuery(prompt: string): string {
  return prompt.replace(/^(recall|search memory|what do you know)[:\s]*/i, "").trim() || "recent work";
}
